@app.route("/download-gpa-pdf")
def download_gpa_pdf():

    student_name = session.get("student_name", "Student")
    reg_no = session.get("reg_no", "N/A")

    gpa_report = session.get("gpa_report", {})

    semester = gpa_report.get("semester", "N/A")
    subjects = gpa_report.get("subjects", [])
    gpa = gpa_report.get("gpa", "N/A")

    pdf_buffer = BytesIO()

    pdf = canvas.Canvas(pdf_buffer)
    pdf.setTitle("GPA Report")

    # =========================
    # TITLE
    # =========================

    pdf.setFont("Helvetica-Bold", 22)

    pdf.drawCentredString(
        300,
        780,
        "GPA CALCULATOR REPORT"
    )

    # =========================
    # STUDENT DETAILS
    # =========================

    pdf.setFont("Helvetica", 12)

    pdf.drawString(
        70,
        735,
        f"Student Name : {student_name}"
    )

    pdf.drawString(
        70,
        710,
        f"Register No  : {reg_no}"
    )

    pdf.drawString(
        70,
        685,
        f"Semester     : Semester {semester}"
    )

    # =========================
    # TABLE
    # =========================

    table_data = [
        ["Subject", "Credits", "Grade"]
    ]

    for subject in subjects:

        table_data.append([
            subject["name"],
            str(subject["credits"]),
            subject["grade"]
        ])

    table = Table(
        table_data,
        colWidths=[240, 100, 100],
        rowHeights=32
    )

    table.setStyle(
        TableStyle([

            ("GRID", (0, 0), (-1, -1), 1, colors.black),

            ("BACKGROUND", (0, 0), (-1, 0), colors.lightgrey),

            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),

            ("FONTNAME", (0, 1), (-1, -1), "Helvetica"),

            ("FONTSIZE", (0, 0), (-1, -1), 11),

            ("ALIGN", (0, 0), (-1, -1), "CENTER"),

            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),

            ("TOPPADDING", (0, 0), (-1, -1), 8),

            ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
        ])
    )

    # =========================
    # TABLE POSITION
    # =========================

    table_width, table_height = table.wrap(
        500,
        400
    )

    table_x = 60
    table_y = 620 - table_height

    table.drawOn(
        pdf,
        table_x,
        table_y
    )

    # =========================
    # GPA RESULT
    # =========================

    pdf.setFont(
        "Helvetica-Bold",
        16
    )

    pdf.drawString(
        70,
        table_y - 45,
        f"Semester GPA : {gpa}"
    )

    # =========================
    # FOOTER
    # =========================

    pdf.setFont(
        "Helvetica",
        10
    )

    pdf.drawCentredString(
        300,
        50,
        "Generated by GPA Calculator"
    )

    # =========================
    # SAVE PDF
    # =========================

    pdf.save()

    pdf_buffer.seek(0)

    return send_file(
        pdf_buffer,
        as_attachment=True,
        download_name=f"Semester_{semester}_GPA_Report.pdf",
        mimetype="application/pdf"
    )
