@app.route("/save-gpa", methods=["POST"])
def save_gpa():

    data = request.get_json()

    semester = data["semester"]
    gpa = data["gpa"]
    credits = data["credits"]
    subjects = data["subjects"]

    # Save semester GPA + credits for CGPA
    if "semester_data" not in session:
        session["semester_data"] = {}

    semester_data = session["semester_data"]

    semester_data[f"Sem {semester}"] = {
        "gpa": gpa,
        "credits": credits
    }

    session["semester_data"] = semester_data

    # Save detailed GPA report for PDF
    session["gpa_report"] = {
        "semester": semester,
        "gpa": gpa,
        "credits": credits,
        "subjects": subjects
    }

    return {
        "message": "GPA data saved successfully"
    }

