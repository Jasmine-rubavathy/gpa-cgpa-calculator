# =========================

@app.route("/download-cgpa-pdf")
def download_cgpa_pdf():

    student_name = session.get("student_name", "Student")
    reg_no = session.get("reg_no", "N/A")
    cgpa = session.get("cgpa", "N/A")
    semester_data = session.get("semester_data", {})

    pdf_buffer = BytesIO()

    pdf = canvas.Canvas(pdf_buffer)

    pdf.setTitle("CGPA Report")

    # Title
    pdf.setFont("Helvetica-Bold", 22)

    pdf.drawCentredString(
        300,
        780,
        "CGPA CALCULATOR REPORT"
    )

    # Student details
    pdf.setFont("Helvetica", 12)

    pdf.drawString(
        70,
        735,
        f"Student Name : {student_name}"
    )

    pdf.drawString(
        70,
        710,
        f"Register No  : {reg_no}"
    )

    # Table
    table_data = [
        ["Semester", "GPA", "Credits"]
    ]

    for semester, data in semester_data.items():

        table_data.append([
            semester,
            str(data["gpa"]),
            str(data["credits"])
        ])

    table = Table(
        table_data,
        colWidths=[180, 120, 120],
        rowHeights=30
    )

    table.setStyle(
        TableStyle([

            ("GRID", (0, 0), (-1, -1), 1, colors.black),

            ("BACKGROUND", (0, 0), (-1, 0), colors.lightgrey),

            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),

            ("FONTNAME", (0, 1), (-1, -1), "Helvetica"),

            ("FONTSIZE", (0, 0), (-1, -1), 11),

            ("ALIGN", (0, 0), (-1, -1), "CENTER"),

            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),

            ("TOPPADDING", (0, 0), (-1, -1), 8),

            ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
        ])
    )

    table_width, table_height = table.wrap(
        500,
        400
    )

    table.drawOn(
        pdf,
        60,
        650 - table_height
    )

    # Overall CGPA
    pdf.setFont(
        "Helvetica-Bold",
        16
    )

    pdf.drawString(
        70,
        650 - table_height - 45,
        f"Overall CGPA : {cgpa}"
    )

    # Footer
    pdf.setFont(
        "Helvetica",
        10
    )

    pdf.drawCentredString(
        300,
        50,
        "Generated by CGPA Calculator"
    )

    pdf.save()

    pdf_buffer.seek(0)

    return send_file(
        pdf_buffer,
        as_attachment=True,
        download_name="CGPA_Report.pdf",
        mimetype="application/pdf"
    )

